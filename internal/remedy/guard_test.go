func TestNoGeneratedEdit(t *testing.T) {
	tests := []struct {
		name   string
		writes []string
		want   string
	}{
		{
			name:   "repository owned files are writable",
			writes: []string{"Makefile.custom.mk", "helm/marge/Chart.yaml", ".ats/main.yaml", ".abs/main.yaml", "go.sum"},
		},
		{
			name:   "renovate-custom.json5 is repository owned",
			writes: []string{"renovate-custom.json5"},
		},
		{
			name:   "a zz_ file at the repository root is refused",
			writes: []string{"zz_generated.app-platform.values.yaml"},
			want:   "generated by giantswarm/github",
		},
		{
			name:   "a zz_ workflow is refused at any depth",
			writes: []string{".github/workflows/zz_generated.pre-commit.yaml"},
			want:   "generated by giantswarm/github",
		},
		{
			name:   "the devctl renovate config is refused",
			writes: []string{"renovate.json5"},
			want:   "generated by devctl",
		},
		{
			name:   "the align-managed pre-commit config is refused",
			writes: []string{"./.pre-commit-config.yaml"},
			want:   "generated by devctl",
		},
		{
			name:   "the generated CircleCI workflows are refused",
			writes: []string{"go.mod", ".circleci/workflows.yml"},
			want:   "generated by devctl",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := NoGeneratedEdit.Refuse(&Request{Writes: tt.writes})
			if tt.want == "" {
				require.Empty(t, got)
				return
			}
			require.Contains(t, got, tt.want)
		})
	}
}

