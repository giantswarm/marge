func TestRequiredChecksGreen(t *testing.T) {
	tests := []struct {
		name     string
		required Required
		want     string
	}{
		{
			name:     "every required context green",
			required: Required{Green: []string{"go-build"}},
		},
		{
			name:     "a failed context refuses",
			required: Required{Failed: []string{"go-build"}},
			want:     "required checks failed: go-build",
		},
		{
			name:     "a pending context waits",
			required: Required{Green: []string{"go-build"}, Pending: []string{"go-test"}},
			want:     "required checks pending: go-test",
		},
		{
			name:     "a context nobody reported waits",
			required: Required{Green: []string{"go-build"}, Missing: []string{"pre-commit"}},
			want:     "required checks not reported: pre-commit",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			require.Equal(t, tt.want, RequiredChecksGreen.Refuse(&Request{Required: tt.required}))
		})
	}
}

